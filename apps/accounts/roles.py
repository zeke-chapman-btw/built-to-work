ROLE_GROUPS={'manager':'BTW Manager','recruiter':'BTW Recruiter','event_staff':'BTW Event Staff'}
ORDINARY_ROLES={'recruiter','event_staff'}

def active_staff(user):
    return bool(getattr(user,'is_authenticated',False) and user.is_active and user.is_staff)
def has_role(user,role):
    if not active_staff(user):return False
    if role=='administrator':return user.is_superuser
    return role in roles_for(user)
def roles_for(user):
    if not hasattr(user,'_staff_group_names'):
        user._staff_group_names=set(user.groups.values_list('name',flat=True))
    return ({'administrator'} if user.is_superuser else set()) | {key for key,name in ROLE_GROUPS.items() if name in user._staff_group_names}
def manager(user):return active_staff(user) and (has_role(user,'administrator') or has_role(user,'manager'))
def managed(user):return bool(roles_for(user))
def require_account_manager(user):
    if not manager(user):raise PermissionDenied

def permission_names(role):
    if role=='recruiter':return {'participants.view_participant','participants.view_participantqualification','participants.view_qualificationcatalogentry','participants.view_participantnote','participants.add_participantnote','participants.change_participantnote'}
    if role=='event_staff':return set()
    if role!='manager':return set()
    return set(MANAGER_PERMISSIONS_V1)

def protected_target(user):
    if user.is_superuser or has_role(user,'manager'):return True
    if user.groups.exclude(name__in=[ROLE_GROUPS[x] for x in ORDINARY_ROLES]).exists():return True
    allowed=permission_names('recruiter')|permission_names('event_staff')
    direct={p.content_type.app_label+'.'+p.codename for p in user.user_permissions.select_related('content_type')}
    return bool(direct-allowed)

def require_target(actor,target):
    require_account_manager(actor)
    if not actor.is_superuser and protected_target(target):raise PermissionDenied('This account requires Administrator review.')

def lock_role_groups():
    return list(Group.objects.select_for_update().filter(name__in=ROLE_GROUPS.values()).order_by('pk'))

def role_configuration(apply=False):
    from django.db import transaction
    from django.db.models import F
    from .models import User
    result=[]
    with transaction.atomic():
        if apply:lock_role_groups()
        for role,name in ROLE_GROUPS.items():
            wanted=permission_names(role)
            group=Group.objects.filter(name=name).first()
            current={p.content_type.app_label+'.'+p.codename for p in group.permissions.select_related('content_type')} if group else set()
            result.append({'role':role,'group':name,'version':ROLE_VERSION,'create':group is None,'add':sorted(wanted-current),'remove':sorted(current-wanted)})
            if apply:
                group,_=Group.objects.get_or_create(name=name)
                permissions=[p for p in Permission.objects.select_related('content_type') if p.content_type.app_label+'.'+p.codename in wanted]
                found={p.content_type.app_label+'.'+p.codename for p in permissions}
                if found != wanted:
                    from django.core.exceptions import ImproperlyConfigured
                    raise ImproperlyConfigured('Role definitions reference missing permissions: '+', '.join(sorted(wanted-found)))
                if current!=wanted or result[-1]['create']:
                    User.objects.filter(groups=group).update(security_revision=F('security_revision')+1)
                    group.permissions.set(permissions)
                    from apps.core.audit import record_audit
                    record_audit(actor=None,action="staff.role.configured",instance=group,source="staff_role_configuration",old_data={"permissions":sorted(current)},new_data={"version":ROLE_VERSION,"permissions":sorted(wanted)},reason="Applied approved versioned staff role definitions; no memberships assigned.")
    return result
